void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == LPUART1)
    {
        // Store received byte into ring buffer
        uint8_t next_head = (rx_head + 1) % RX_BUF_SIZE;
        if (next_head != rx_tail)
        {
            rx_buf[rx_head] = rx_byte;
            rx_head = next_head;
        }

        // Re-arm interrupt for next byte
        HAL_UART_Receive_IT(&hlpuart1, &rx_byte, 1);
    }
}

// --- TIM Period Elapsed Callback (1ms Tick for Timer & Software PWM) ---
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2)
    {
        // 1. Manage 1-Second Timer
        ms_timer++;
        if (ms_timer >= 1000)
        {
            ms_timer = 0;
            flag_1s = true;
        }

        // 2. Software PWM for PA5 (Green LED)
        // PWM Period = 100ms (100 steps of 1ms)
        pwm_counter++;
        if (pwm_counter >= 100)
        {
            pwm_counter = 0;
        }

        // Determine target brightness
        uint8_t target_brightness = is_safe_mode ? 1 : battery_level;

        // Set LED output based on PWM counter
        if (pwm_counter < target_brightness)
        {
            HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);
        }
        else
        {
            HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);
        }
    }
}

// --- EXTI Callback (Button Reset with Debounce) ---
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    if (GPIO_Pin == GPIO_PIN_13) // PC13
    {
        uint32_t current_time = HAL_GetTick(); // Using SysTick for debounce

        // 150ms Software Debounce
        if (current_time - last_button_time >= 150)
        {
            last_button_time = current_time;

            // Reset System States
            battery_level = 100;
            charge_seconds = 0;
            is_safe_mode = false;
            ms_timer = 0; // Synchronize 1s timer

            printf("[INFO] System Reset! Battery: 100%%, Timer: 0 / 15 s\r\n");
        }
    }
}
