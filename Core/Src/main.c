	            if (cmd == '+')
	            {
	                if (battery_level <= 90) battery_level += 10;
	                else battery_level = 100;
	                printf("[CMD] Battery Increased: %d%%\r\n", battery_level);
	            }
	            else if (cmd == '-')
	            {
	                if (battery_level >= 10) battery_level -= 10;
	                else battery_level = 0;
	                printf("[CMD] Battery Decreased: %d%%\r\n", battery_level);
	            }
